#!/usr/bin/env node
// Generate TypeScript declarations from the vendored lexicons in crates/pds/lexicons.
//
// One `<namespace>.d.ts` per lexicon namespace (com.atproto.repo, app.bsky.feed, …) plus an
// `index.d.ts` mapping every query/procedure NSID to its params, input, and output types, and
// every record collection to its record type. Plain .mjs with no dependencies so the drift
// check (`--check`) runs anywhere `just ci-pds` does, with no pnpm install.
//
// Usage: node tools/lexgen/generate.mjs [--check]

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const lexiconDir = path.join(root, 'crates/pds/lexicons');
const outDir = path.join(here, 'types');
const check = process.argv.includes('--check');

const HEADER =
  '// Generated by tools/lexgen/generate.mjs from crates/pds/lexicons — do not edit.\n' +
  '// Regenerate with `just lexgen`.';

function walk(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))
    .filter((f) => f.endsWith('.json'));
}

const docs = new Map(); // nsid -> lexicon document
for (const file of walk(lexiconDir).sort()) {
  const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
  docs.set(doc.id, doc);
}

const namespaceOf = (nsid) => nsid.slice(0, nsid.lastIndexOf('.'));
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const alias = (ns) => ns.replaceAll('.', '_');

/** Exported type name of `nsid#def` inside its namespace file. */
function typeName(nsid, def) {
  const base = pascal(nsid.slice(nsid.lastIndexOf('.') + 1));
  return def === 'main' ? base : base + pascal(def);
}

/** Emits one namespace file; tracks the other namespaces it imports. */
class Emitter {
  constructor(ns) {
    this.ns = ns;
    this.imports = new Set();
    this.decls = [];
    this.names = new Set();
  }

  declare(name, body) {
    if (this.names.has(name)) throw new Error(`${this.ns}: duplicate generated type ${name}`);
    this.names.add(name);
    this.decls.push(`export type ${name} = ${body};`);
  }

  ref(fromNsid, ref) {
    const [target, def = 'main'] = ref.startsWith('#') ? [fromNsid, ref.slice(1)] : ref.split('#');
    const doc = docs.get(target);
    // A ref into a namespace Custos does not vendor (proxied AppView views) carries no
    // schema here, so it types as unknown rather than failing the whole generation.
    if (!doc || !doc.defs[def]) return 'unknown';
    const name = typeName(target, def);
    const ns = namespaceOf(target);
    if (ns === this.ns) return name;
    this.imports.add(ns);
    return `${alias(ns)}.${name}`;
  }

  type(nsid, schema, selfId) {
    switch (schema.type) {
      case 'string':
        if (schema.const !== undefined) return JSON.stringify(schema.const);
        if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
        if (schema.knownValues) {
          return [...schema.knownValues.map((v) => JSON.stringify(v)), '(string & {})'].join(' | ');
        }
        return 'string';
      case 'integer':
        return schema.const !== undefined ? String(schema.const) : 'number';
      case 'boolean':
        return schema.const !== undefined ? String(schema.const) : 'boolean';
      case 'bytes':
        return '{ $bytes: string }';
      case 'cid-link':
        return '{ $link: string }';
      case 'blob':
        return 'BlobRef';
      case 'unknown':
        return '{ [key: string]: unknown }';
      case 'array':
        return `Array<${this.type(nsid, schema.items)}>`;
      case 'ref':
        return this.ref(nsid, schema.ref);
      case 'union': {
        const members = schema.refs.map((r) => this.ref(nsid, r));
        if (!schema.closed) members.push('{ $type: string }');
        return [...new Set(members)].join(' | ') || 'never';
      }
      case 'object':
      case 'params':
        return this.object(nsid, schema, selfId);
      default:
        throw new Error(`${nsid}: unsupported schema type ${schema.type}`);
    }
  }

  object(nsid, schema, selfId) {
    const required = new Set(schema.required ?? []);
    const nullable = new Set(schema.nullable ?? []);
    const lines = [];
    if (selfId) lines.push(`  $type?: ${JSON.stringify(selfId)};`);
    for (const [key, prop] of Object.entries(schema.properties ?? {})) {
      const t = this.type(nsid, prop) + (nullable.has(key) ? ' | null' : '');
      lines.push(`  ${key}${required.has(key) ? '' : '?'}: ${t};`);
    }
    return lines.length ? `{\n${lines.join('\n')}\n}` : 'Record<string, never>';
  }

  /** Body of an XRPC input/output: JSON schema, raw bytes, or nothing. */
  body(nsid, io) {
    if (!io) return 'undefined';
    if (!io.schema) return io.encoding === 'application/json' ? 'unknown' : 'Uint8Array';
    return this.type(nsid, io.schema);
  }

  render() {
    const imports = [...this.imports]
      .sort()
      .map((ns) => `import type * as ${alias(ns)} from './${ns}.js';`);
    const blob = this.decls.some((d) => d.includes('BlobRef'))
      ? ["import type { BlobRef } from './blob.js';"]
      : [];
    const preamble = [...blob, ...imports];
    return [HEADER, ...(preamble.length ? ['', ...preamble] : []), '', ...this.decls, ''].join('\n');
  }
}

const emitters = new Map();
const methods = []; // [nsid, ns, baseName, hasParams]
const records = []; // [nsid, ns, name]

for (const [nsid, doc] of docs) {
  const ns = namespaceOf(nsid);
  if (!emitters.has(ns)) emitters.set(ns, new Emitter(ns));
  const em = emitters.get(ns);
  for (const [def, schema] of Object.entries(doc.defs)) {
    const name = typeName(nsid, def);
    const fqid = def === 'main' ? nsid : `${nsid}#${def}`;
    switch (schema.type) {
      case 'query':
      case 'procedure':
        em.declare(`${name}Params`, schema.parameters ? em.type(nsid, schema.parameters) : 'undefined');
        em.declare(`${name}Input`, em.body(nsid, schema.input));
        em.declare(`${name}Output`, em.body(nsid, schema.output));
        methods.push([nsid, ns, name]);
        break;
      case 'record':
        em.declare(name, em.object(nsid, schema.record, fqid).replace('$type?:', '$type:'));
        records.push([nsid, ns, name]);
        break;
      case 'token':
        em.declare(name, JSON.stringify(fqid));
        break;
      case 'object':
        em.declare(name, em.object(nsid, schema, fqid));
        break;
      case 'subscription':
        break; // event streams are not request/response shapes
      default:
        em.declare(name, em.type(nsid, schema));
    }
  }
}

const files = new Map();
files.set(
  'blob.d.ts',
  `${HEADER}\n\n/** A blob reference as it appears in JSON (lexicon \`blob\` type). */\n` +
    'export type BlobRef = {\n  $type: \'blob\';\n  ref: { $link: string };\n  mimeType: string;\n  size: number;\n};\n',
);
for (const [ns, em] of emitters) files.set(`${ns}.d.ts`, em.render());

const nsImports = [...emitters.keys()].sort().map((ns) => `import type * as ${alias(ns)} from './${ns}.js';`);
const methodLines = methods
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([nsid, ns, name]) =>
      `  ${JSON.stringify(nsid)}: {\n` +
      `    params: ${alias(ns)}.${name}Params;\n` +
      `    input: ${alias(ns)}.${name}Input;\n` +
      `    output: ${alias(ns)}.${name}Output;\n  };`,
  );
const recordLines = records
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([nsid, ns, name]) => `  ${JSON.stringify(nsid)}: ${alias(ns)}.${name};`);
files.set(
  'index.d.ts',
  [
    HEADER,
    '',
    "export type { BlobRef } from './blob.js';",
    ...nsImports,
    '',
    '/** Every vendored query/procedure, keyed by NSID. */',
    `export type XrpcMethods = {\n${methodLines.join('\n')}\n};`,
    '',
    '/** Every vendored record type, keyed by collection NSID. */',
    `export type Records = {\n${recordLines.join('\n')}\n};`,
    '',
  ].join('\n'),
);

if (check) {
  const existing = fs.existsSync(outDir) ? fs.readdirSync(outDir).sort() : [];
  const wanted = [...files.keys()].sort();
  const drift = [
    ...wanted.filter((f) => {
      const p = path.join(outDir, f);
      return !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== files.get(f);
    }),
    ...existing.filter((f) => !files.has(f)),
  ];
  if (drift.length) {
    console.error(`✗ lexgen drift in tools/lexgen/types: ${drift.join(', ')} — run \`just lexgen\``);
    process.exit(1);
  }
  console.log(`✓ lexgen parity: ${files.size} generated files match ${docs.size} lexicons`);
} else {
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  for (const [f, content] of files) fs.writeFileSync(path.join(outDir, f), content);
  console.log(`wrote ${files.size} files to tools/lexgen/types`);
}
